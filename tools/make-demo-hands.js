'use strict';
const fs = require('fs');
const path = require('path');
const { generateDemoHands } = require('../app/renderer/demo-gen.js');
const db = generateDemoHands();
const N = db.count;
const out = path.join(__dirname, '..', 'app', 'data', 'demo-hands.json');
