'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('mda', {
  dbMeta: () => ipcRenderer.invoke('db:meta'),
  dbCol: (name) => ipcRenderer.invoke('db:col', name),
  replaysFor: (ids) => ipcRenderer.invoke('db:replays', Array.from(ids)),
  playersList: (q, limit) => ipcRenderer.invoke('players:list', q, limit),
  playerMeta: (pid) => ipcRenderer.invoke('player:meta', pid),
  playerCol: (pid, name) => ipcRenderer.invoke('player:col', pid, name),
  playersCc: () => ipcRenderer.invoke('players:cc'),
  playersFind: (list) => ipcRenderer.invoke('players:find', list),
  saveAliases: (list) => ipcRenderer.invoke('aliases:save', list),
  playerReplays: (pid, ids) => ipcRenderer.invoke('player:replays', pid, Array.from(ids)),
  demoDb: () => ipcRenderer.invoke('db:demo'),
  dbInfo: () => ipcRenderer.invoke('db:info'),
  deleteDb: () => ipcRenderer.invoke('db:delete'),
  runImport: (opts) => ipcRenderer.invoke('import:run', opts),
  estimate: (nicks) => ipcRenderer.invoke('import:estimate', nicks),
  baseLocation: () => ipcRenderer.invoke('base:location'),
  pickBaseDir: () => ipcRenderer.invoke('base:pick'),
  onEvBg: (cb) => { ipcRenderer.removeAllListeners('ev:bg'); ipcRenderer.on('ev:bg', (_e, m) => cb(m)); },
  getPerf: () => ipcRenderer.invoke('perf:get'),
  setPerf: (m) => ipcRenderer.invoke('perf:set', m),
  onMigrate: (cb) => { ipcRenderer.removeAllListeners('db:migrate'); ipcRenderer.on('db:migrate', (_e, m) => cb(m)); },
  onProgress: (cb) => { ipcRenderer.removeAllListeners('import:progress'); ipcRenderer.on('import:progress', (_e, m) => cb(m)); },
  pick: (mode) => ipcRenderer.invoke('import:pick', mode),
  // путь перетащенного файла или папки: File нельзя передать списком (FileList через contextBridge приходит пустым),
  // поэтому рендерер спрашивает путь у каждого File по одному (так описано в документации Electron)
  pathOf: (file) => { try { return webUtils.getPathForFile(file) || ''; } catch (e) { return ''; } },
  droppedPaths: (paths) => ipcRenderer.invoke('import:paths', Array.from(paths || []).map(String)),
  version: () => ipcRenderer.invoke('app:version'),
  capture: () => ipcRenderer.invoke('app:capture'),
  resultsData: () => ipcRenderer.invoke('results:data'),
  social: {
    status: () => ipcRenderer.invoke('social:status'),
    server: (o) => ipcRenderer.invoke('social:server', o),
    call: (m, p, b) => ipcRenderer.invoke('social:call', m, p, b),
    logout: () => ipcRenderer.invoke('social:logout'),
    img: (p) => ipcRenderer.invoke('social:img', p),
    on: (fn) => { ipcRenderer.on('social:ev', (_e, kind, data) => fn(kind, data)); }
  },
  newsGet: (force) => ipcRenderer.invoke('news:get', !!force),
  liveList: (y, m, force) => ipcRenderer.invoke('live:list', +y, +m, !!force),
  liveFest: (id, force) => ipcRenderer.invoke('live:fest', +id, !!force),
  livePass: (kind, a, b) => ipcRenderer.invoke('live:pass', String(kind), +a, +b || 0),
  liveRates: () => ipcRenderer.invoke('live:rates'),
  liveSum: (id, v) => ipcRenderer.invoke('live:sum', id == null ? null : +id, v),
  streamsLive: (logins) => ipcRenderer.invoke('streams:live', Array.from(logins || []).map(String)),
  twitchStatus: () => ipcRenderer.invoke('twitch:status'),
  twitchSet: (id, sec) => ipcRenderer.invoke('twitch:set', String(id || ''), String(sec || '')),
  twitchClear: () => ipcRenderer.invoke('twitch:clear'),
  twitchLive: () => ipcRenderer.invoke('twitch:live'),
  // только для автотестов: выбрать папку без диалога
  scanPathsForTest: (process.env.MDALAB_EVAL || process.env.MDALAB_SNAPSHOT || process.env.MDALAB_TEST) ? (paths) => ipcRenderer.invoke('import:paths', paths) : undefined
});
