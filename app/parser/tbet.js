'use strict';
// 3-бет и что было после него (с 0.7.23). Считается по записи раздачи в виде реплеера: rec.pl — места по кругу
// стола [позиция, стек в BB, …], rec.ev — действия [улица, место, тип, сумма «до» в BB, олл-ин]. Тот же расчёт
// и при разборе историй (parse.js строит такую же лёгкую запись), и при обновлении старой базы (migrate.js).
//
// fp / fop — позиция игрока и открывающего «как в Hand2Note» во вкладке 3-бет: считается назад от баттона —
// CO (1 место до BTN), HJ (2), MP (3–4), EP (5 и дальше); SB, BB, BTN — как есть.
// Коды: 0 EP, 1 MP, 2 HJ, 3 CO, 4 BTN, 5 SB, 6 BB (-1 — неизвестно).
// t3r — ответ соперников на рейз игрока поверх ровно одного рейза (3-бет, сквиз, 3-бет против изолейта):
// 0 все сбросили, 1 колл, 2 4-бет, 3 4-бет олл-ином (-1 — не было); +4 — открывающий сбросил на этот рейз.
// t4 — ход игрока против 4-бета: 0 фолд, 1 колл, 2 5-бет; +4 — 5-бет был невозможен (4-бет олл-ином или на весь стек игрока);
// +8 — 4-бет поставил не открывающий (холодный 4-бет).
// sqc (0.7.57) — fine-позиция первого коллера открытия до хода игрока (-1 — коллеров не было).
// v3 — ход игрока против 3-бета на своё открытие (до игрока никто не рейзил): 0 фолд, 1 колл, 2 4-бет, 3 4-бет олл-ином
// (-1 — 3-бета не было или хода игрока после него не случилось);
// v3a — 3-бет соперника «олл-ин»: явный пуш, ставка на весь стек 3-бетящего ИЛИ размер, покрывающий эффективный стек —
// стек открывающего и коллеров открытия (даже если у 3-бетящего остались фишки). -1 — 3-бета не было.
// v3o — между открытием и 3-бетом opening коллировали другие игроки (1/0, -1 — 3-бета не было) — «сквиз пот»: 3-бет поднял банк поверх колла(ов);
// v3c — МЕЖДУ 3-бетом и ходом игрока другие игроки вступали в игру — кол или рейз, не фолд (1/0, -1 — 3-бета не было) — «3b пот 3+».
// Действия других ПОСЛЕ хода игрока (например, колл его олл-ина) в v3c не считаются: банк для решения игрока уже сложился.
// v3e (0.7.44) — чем вступили за спиной до хода игрока: 0 никто, 1 только колы (включая короткий олл-ин, не превышающий размер 3-бета),
// 2 был рейз поверх 3-бета (холодный 4-бет, хотя бы один; колы при этом могли быть). -1 — 3-бета не было.
// v3p (0.7.44) — позиция игрока относительно 3-бетящего ПОСТФЛОП: 1 — игрок в позиции (действует после 3-бетящего), 0 — вне позиции. -1 — 3-бета не было.
// v3q (0.7.49) — fine-позиция 3-бетящего (первого агрессора — трибетера или сквизера): 0 EP … 6 BB, -1 — не было/неизвестна.
// v3s (0.7.50) — стек 3-бетящего в начале раздачи, BB×10 (для asR — стек того, кто 3-бетнул ваше открытие; -1 — не было).
// asC (0.7.47, «сквиз пот» — вы колером): игрок заколлировал чужое открытие (ровно один рейз до него, без лимпов до открытия;
// коллеры открытия до и после него допускаются), и за спиной подняли поверх — сквиз. Коды зеркальны семейству v3:
// c3 — ход игрока против сквиза (0 фолд, 1 колл, 2 4-бет, 3 4-бет олл-ином; -1 — сквиза не было или хода не случилось);
// c3a — сквиз «олл-ин» эффективно (пуш, весь стек сквизера или ставка, покрывающая стеки открывающего и всех коллеров);
// c3e — вступили между сквизом и ходом игрока (0/1 колы/2 рейз); c3p — позиция игрока относительно сквизера постфлоп (1 IP / 0 OOP).
const ACT = new Set(['f', 'x', 'c', 'b', 'r']);
const FIX = { CO: 3, BTN: 4, SB: 5, BB: 6 };

function fineOf(rec, k) {
  if (k == null || k < 0 || !rec.pl[k]) return -1;
  const p = rec.pl[k][0]; if (FIX[p] != null) return FIX[p];
  const N = rec.pl.length, b = rec.pl.findIndex(x => x[0] === 'BTN'); if (b < 0) return -1;
  const d = (b - k + N) % N;
  return d === 2 ? 2 : d === 3 || d === 4 ? 1 : 0;
}

function tbetOf(rec, s) {
  const out = { fp: fineOf(rec, s), fop: -1, t3r: -1, t4: -1, v3: -1, v3a: -1, v3o: -1, v3c: -1, v3e: -1, v3p: -1, c3: -1, c3a: -1, c3e: -1, c3p: -1, v3q: -1, c3q: -1, v3s: -1, v3k: -1, v3x: -1, v3z: -1, v3f: -1, sqc: -1 };
  const p = rec.ev.filter(e => e[0] === 0 && ACT.has(e[2]));
  const hi = p.findIndex(e => e[1] === s); if (hi < 0) return out;
  const before = p.slice(0, hi), rz = before.filter(e => e[2] === 'r' || e[2] === 'b');
  if (rz.length) out.fop = fineOf(rec, rz[0][1]);
  // sqc (0.7.57) — позиция первого коллера открытия до хода игрока (для вкладки «Сквиз»: открывающий + коллер), -1 — коллеров не было
  if (rz.length === 1) { const fc = before.slice(before.indexOf(rz[0]) + 1).find(e => e[2] === 'c'); if (fc) out.sqc = fineOf(rec, fc[1]); }
  // asC: игрок заколлировал чужое открытие (ровно один рейз до него, до открытия — ни лимпов), и за спиной подняли поверх (сквиз)
  if (rz.length === 1 && p[hi][2] === 'c' && !before.slice(0, before.indexOf(rz[0])).some(e => e[2] === 'c')) {
    const afterC = p.slice(hi + 1);
    const rs = afterC.findIndex(e => e[1] !== s && (e[2] === 'r' || e[2] === 'b'));
    if (rs >= 0) {
      const sq = afterC[rs], stS = rec.pl[sq[1]] ? rec.pl[sq[1]][1] : 0;
      // «олл-ин» сквиза — эффективно: покрывает стеки открывающего и всех коллеров (включая игрока)
      const eff = Math.max(...[rz[0]].concat(before.slice(before.indexOf(rz[0]) + 1).filter(e => e[2] === 'c'), afterC.slice(0, rs).filter(e => e[2] === 'c')).map(e => (rec.pl[e[1]] || [])[1] || 0).concat([rec.pl[s] ? rec.pl[s][1] : 0]));
      out.c3a = sq[4] || (stS > 0 && sq[3] >= stS - 0.001) || (eff > 0 && sq[3] >= eff - 0.001) ? 1 : 0;
      const afterS = afterC.slice(rs + 1), nx = afterS.find(e => e[1] === s);
      const seg = nx ? afterS.slice(0, afterS.indexOf(nx)) : afterS;
      let entry = 0;
      for (const e of seg) {
        if (e[1] === s || e[2] === 'f') continue;
        const isRaise = (e[2] === 'r' || e[2] === 'b') && e[3] > sq[3] + 0.001; // рейз больше сквиза; короткий олл-ин ≤ сквиза — кол
        if (isRaise) { entry = 2; break; }
        if (entry === 0) entry = 1;
      }
      out.c3e = entry;
      const N = rec.pl.length;
      let bi = rec.pl.findIndex(x => x[0] === 'BTN');
      if (bi < 0 && N === 2) bi = rec.pl.findIndex(x => x[0] === 'SB');
      if (bi >= 0 && rec.pl[sq[1]]) { const o = (k) => ((k - bi - 1 + N) % N) + 1; out.c3p = o(s) > o(sq[1]) ? 1 : 0; }
      if (nx) out.c3 = nx[2] === 'f' ? 0 : nx[2] === 'c' ? 1 : nx[4] ? 3 : 2;
      out.c3q = fineOf(rec, sq[1]); // fine-позиция сквизера
    }
  }
  // против 3-бета (вкладка v3B): игрок открылся (до него никто не входил — ни рейзов, ни лимпов) и следом получил ререйз
  if (!rz.length && !before.some(e => e[2] === 'c') && (p[hi][2] === 'r' || p[hi][2] === 'b')) {
    const after0 = p.slice(hi + 1);
    const r3 = after0.findIndex(e => e[1] !== s && (e[2] === 'r' || e[2] === 'b'));
    if (r3 >= 0) {
      const three = after0[r3], st3 = rec.pl[three[1]] ? rec.pl[three[1]][1] : 0;
      // «олл-ин» — эффективно: явный пуш, весь стек 3-бетящего или ставка, покрывающая стек открывающего и коллеров открытия
      const eff = Math.max(rec.pl[s] ? rec.pl[s][1] : 0, ...after0.slice(0, r3).filter(e => e[2] === 'c').map(e => (rec.pl[e[1]] || [])[1] || 0));
      out.v3a = three[4] || (st3 > 0 && three[3] >= st3 - 0.001) || (eff > 0 && three[3] >= eff - 0.001) ? 1 : 0;
      out.v3o = after0.slice(0, r3).some(e => e[2] === 'c') ? 1 : 0; // открытие коллировали до 3-бета — «сквиз пот»
      const afterR3 = after0.slice(r3 + 1), nx = afterR3.find(e => e[1] === s);
      const seg = nx ? afterR3.slice(0, afterR3.indexOf(nx)) : afterR3; // между 3-бетом и ходом игрока
      // v3c: вступали вообще (не фолд); v3e: чем именно — кол (включая короткий олл-ин не больше 3-бета) или рейз поверх
      let entry = 0;
      for (const e of seg) {
        if (e[1] === s || e[2] === 'f') continue;
        const isRaise = (e[2] === 'r' || e[2] === 'b') && e[3] > three[3] + 0.001; // рейз больше 3-бета; короткий олл-ин ≤ 3-бета — это кол
        if (isRaise) { entry = 2; break; }
        if (entry === 0) entry = 1;
      }
      out.v3c = seg.some(e => e[1] !== s && e[2] !== 'f') ? 1 : 0;
      out.v3e = entry;
      // v3k (0.7.55) — сколько разных соперников вступили (кол или рейз) между 3-бетом и ходом игрока; v3x — первый рейз поверх 3-бета
      // был олл-ином (пуш или ставка на весь стек вступившего): 1 / 0, -1 — рейза поверх не было
      out.v3k = new Set(seg.filter(e => e[1] !== s && e[2] !== 'f').map(e => e[1])).size;
      { const ov = seg.find(e => e[1] !== s && (e[2] === 'r' || e[2] === 'b') && e[3] > three[3] + 0.001); if (ov) { const st = rec.pl[ov[1]] ? rec.pl[ov[1]][1] : 0; out.v3x = ov[4] || (st > 0 && ov[3] >= st - 0.001) ? 1 : 0; } }
      // v3p: позиция игрока относительно 3-бетящего постфлоп (позже по ходу — в позиции): порядок от блайндов к баттону.
      // В хедз-апе метки BTN в записи нет — баттоном является SB (он и действует последним постфлоп)
      const N = rec.pl.length;
      let bi = rec.pl.findIndex(x => x[0] === 'BTN');
      if (bi < 0 && N === 2) bi = rec.pl.findIndex(x => x[0] === 'SB');
      if (bi >= 0 && rec.pl[three[1]]) {
        const o = (k) => ((k - bi - 1 + N) % N) + 1; // SB=1 … BTN=N (кто позже — тот в позиции)
        out.v3p = o(s) > o(three[1]) ? 1 : 0;
      }
      if (nx) out.v3 = nx[2] === 'f' ? 0 : nx[2] === 'c' ? 1 : nx[4] ? 3 : 2;
      // v3z (0.7.55) — размер 3-бета «до», BB×100 (в разах от открытия — v3z / size); v3f — ваш ход против 5-бета после вашего 4-бета:
      // 0 фолд, 1 колл, 2 рейз; -1 — 5-бета не было (или вы не 4-бетили)
      out.v3z = Math.round(three[3] * 100);
      if (nx && (nx[2] === 'r' || nx[2] === 'b')) { const a5 = afterR3.slice(afterR3.indexOf(nx) + 1), r5 = a5.find(e => e[1] !== s && (e[2] === 'r' || e[2] === 'b') && e[3] > nx[3] + 0.001); if (r5) { const h5 = a5.slice(a5.indexOf(r5) + 1).find(e => e[1] === s); if (h5) out.v3f = h5[2] === 'f' ? 0 : h5[2] === 'c' ? 1 : 2; } }
      out.v3q = fineOf(rec, three[1]); // fine-позиция 3-бетящего (первого агрессора)
      out.v3s = rec.pl[three[1]] ? Math.round(rec.pl[three[1]][1] * 10) : -1; // стек 3-бетящего, BB×10
    }
  }
  if (rz.length !== 1 || p[hi][2] !== 'r') return out;
  const after = p.slice(hi + 1);
  const first = after.find(e => e[1] !== s && e[2] !== 'f');
  out.t3r = !first ? 0 : first[2] === 'c' ? 1 : first[4] ? 3 : 2;
  // +4 — сбросил сам открывающий (тот, кого 3-бетили), даже если до него кто-то за спиной вступил в игру
  { const oa = after.find(e => e[1] === rz[0][1]); if (oa && oa[2] === 'f') out.t3r += 4; }
  const r4 = after.findIndex(e => e[1] !== s && (e[2] === 'r' || e[2] === 'b'));
  if (r4 < 0) return out;
  const nx = after.slice(r4 + 1).find(e => e[1] === s); if (!nx) return out;
  const four = after[r4], stack = rec.pl[s] ? rec.pl[s][1] : 0;
  // +8 — 4-бет «в холодную»: его поставил не открывающий, а игрок, который ещё не вкладывался (ходит после вас)
  out.t4 = (nx[2] === 'f' ? 0 : nx[2] === 'r' || nx[2] === 'b' ? 2 : 1) + (four[4] || four[3] >= stack - 0.001 ? 4 : 0) + (four[1] !== rz[0][1] ? 8 : 0);
  return out;
}

module.exports = { tbetOf, fineOf };
